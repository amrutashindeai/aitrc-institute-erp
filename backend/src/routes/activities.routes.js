const express = require('express');
const authenticate = require('../middleware/authenticate');
const { authorize } = require('../middleware/authorize');
const validate = require('../middleware/validate');
const Activities = require('../controllers/activities.controller');
const V = require('../validators/activity.validators');
const { z } = require('zod');
const router = express.Router();
router.use(authenticate);
router.get('/', Activities.list);
router.post('/', authorize('DIRECTOR', 'PRINCIPAL', 'HOD', 'COMMITTEE_HEAD', 'ADMIN'), validate(V.activityCreate), Activities.create);
router.get('/:id', Activities.getById);
router.patch('/:id', authorize('DIRECTOR', 'PRINCIPAL', 'HOD', 'COMMITTEE_HEAD', 'ADMIN'), validate(V.activityPatch), Activities.update);
router.post('/:id/assignments', authorize('DIRECTOR', 'PRINCIPAL', 'HOD', 'COMMITTEE_HEAD', 'ADMIN'), validate(V.assignmentCreate), Activities.assign);
router.patch('/:id/assignments/:assignmentId', authorize('DIRECTOR', 'PRINCIPAL', 'HOD', 'COMMITTEE_HEAD', 'ADMIN'), validate(V.assignmentPatch), Activities.updateAssignment);
router.post('/:id/start', validate(V.workflowComment), Activities.start);
router.post('/:id/submit', validate(V.workflowComment), Activities.submit);
router.post('/:id/return', authorize('DIRECTOR', 'PRINCIPAL', 'HOD', 'COMMITTEE_HEAD', 'ADMIN'), validate(V.returnComment), Activities.returnActivity);
router.post('/:id/verify', authorize('DIRECTOR', 'PRINCIPAL', 'HOD', 'COMMITTEE_HEAD', 'ADMIN'), validate(V.workflowComment), Activities.verify);
router.post('/:id/close', authorize('DIRECTOR', 'PRINCIPAL', 'HOD', 'ADMIN'), validate(V.workflowComment), Activities.close);
router.get('/:id/history', Activities.history);
router.get('/:id/evidence-requirements', Activities.evidenceRequirements);
module.exports = router;
